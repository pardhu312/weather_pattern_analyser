import pandas as pd

from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder

from .training_data import (
    FEATURES,
    TARGET,
    prepare_training_data,
)


def random_forest_feature_importance(
    df: pd.DataFrame,
) -> dict:

    prepared = prepare_training_data(df)

    if not prepared["ready"]:
        return {
            "ready": False,
            "message": prepared["message"],
            "usable_training_rows": prepared.get(
                "usable_rows",
                0,
            ),
        }

    train = prepared["train"]

    X_train = train[FEATURES]
    y_train = train[TARGET]

    categorical_features = ["city"]

    numerical_features = [
        feature
        for feature in FEATURES
        if feature != "city"
    ]

    preprocessor = ColumnTransformer(
        transformers=[
            (
                "city",
                OneHotEncoder(
                    handle_unknown="ignore"
                ),
                categorical_features,
            ),
            (
                "numeric",
                "passthrough",
                numerical_features,
            ),
        ]
    )

    model = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor,
            ),
            (
                "model",
                RandomForestRegressor(
                    n_estimators=300,
                    random_state=42,
                    n_jobs=-1,
                ),
            ),
        ]
    )

    model.fit(
        X_train,
        y_train,
    )

    fitted_preprocessor = model.named_steps[
        "preprocessor"
    ]

    fitted_model = model.named_steps[
        "model"
    ]

    feature_names = (
        fitted_preprocessor
        .get_feature_names_out()
    )

    importances = fitted_model.feature_importances_

    importance_df = pd.DataFrame({
        "feature": feature_names,
        "importance": importances,
    })

    # Clean names generated by ColumnTransformer
    importance_df["feature"] = (
        importance_df["feature"]
        .str.replace(
            "city__",
            "",
            regex=False,
        )
        .str.replace(
            "numeric__",
            "",
            regex=False,
        )
    )

    importance_df = (
        importance_df
        .sort_values(
            "importance",
            ascending=False,
        )
        .reset_index(drop=True)
    )

    return {
        "ready": True,
        "model": "Random Forest",
        "training_rows": int(len(train)),
        "feature_importance": [
            {
                "feature": row["feature"],
                "importance": round(
                    float(row["importance"]),
                    6,
                ),
            }
            for _, row in importance_df.iterrows()
        ],
    }